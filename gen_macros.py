"""Write results/results_macros.tex: every number quoted in the manuscript comes from here."""
import json
import numpy as np

perf = {r["case"]: r for r in json.load(open("results/performance_table.json"))}
bench = {r["plant"]: r for r in json.load(open("results/benchmark_table.json"))}
hist = json.load(open("results/rsm_history_table.json"))
mc = json.load(open("results/montecarlo.json"))
rga = json.load(open("results/rga.json"))
best = min(hist, key=lambda h: h["IAE"])
init = hist[0]

def f(x, d=2):
    return f"{x:.{d}f}"

M = {}
def put(name, val): M[name] = val

# PIDDec parameters (Kp, Ti, Td, a, b, c)
for nm, v in zip(["Kp", "Ti", "Td", "a", "b", "c"], best["center"]):
    if v == 0:
        s = "0"
    elif abs(v) >= 1e-2:
        s = f"{v:.4g}"
    else:
        m, e = f"{v:.2e}".split("e")
        s = rf"{m}\times10^{{{int(e)}}}"
    put("pid" + nm, s)
put("rsmIterations", str(len(hist)))
put("rsmBestIteration", str(best["iteration"]))
put("rsmMinRtwo", f(min(h["r2"] for h in hist), 3))
put("rsmRuns", str(729 * len(hist)))
put("IAErelInit", f(init["IAE_rel"], 2))

def caseval(case, key, d=2, scale=1.0):
    return f(perf[case][key] * scale, d)

for tag, case in [("None", "No decoupler"), ("Static", "Static decoupler"), ("Filt", "Filtered ideal D21"),
                  ("Pid", "PIDDec (RSM)"), ("NoneFast", "No decoupler, Kp22 x7"),
                  ("StaticFast", "Static decoupler, Kp22 x103"), ("FiltFast", "Filtered ideal D21, Kp22 x103"),
                  ("PidFast", "PIDDec (RSM), Kp22 x103")]:
    r = perf[case]
    put("IAEset" + tag, f(r["IAE_rel_setpoint"], 3))
    put("IAEload" + tag, f(r["IAE_rel_load"], 2))
    put("ov" + tag, f(r["interaction_overshoot_%"], 1))
    put("Tnf" + tag, f(r["T95_s"], 0) if r["T95_s"] is not None else "--")
    put("pole" + tag, f"{r['slowest_pole']:.2e}".replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + "}")
    gm = r["gain_margin"]
    put("gm" + tag, r"$>50$" if gm == float("inf") else f(gm, 1))
    put("uMax" + tag, f(r["u2_abs_range_%"][1], 0))
put("speedup", f(perf["No decoupler"]["T95_s"] / perf["PIDDec (RSM), Kp22 x103"]["T95_s"], 0))
put("lambdaStatic", f(rga["lambda11_static"], 2))

for k, tag in [("none", "None"), ("static", "Static"), ("filt", "Filt"), ("pid", "Pid")]:
    st = np.mean(mc[k]["stable"]) * 100
    put("mcStable" + tag, f(st, 0))
    put("mcOvMed" + tag, f(np.median(mc[k]["ov"]), 1))
    put("mcOvPnf" + tag, f(np.percentile(mc[k]["ov"], 95), 1))
    put("mcTnfMed" + tag, f(np.nanmedian(mc[k]["T95"]), 0))

for n, tag in [("Hylte", "Hylte"), ("WoodBerry", "WB")]:
    b = bench[n]
    put("bench" + tag + "StaticRule", f(b["static_rule"], 3))
    put("bench" + tag + "StaticOpt", f(b["static_opt"], 3))
    put("bench" + tag + "Ideal", f(b["ideal"], 4 if b["ideal"] < 0.01 else 3))
    put("bench" + tag + "Pid", f(b["pid"], 3))
    put("bench" + tag + "Iter", str(b["iterations"]))
    b2 = json.load(open(f"results/bench2_{n}.json"))
    put("bench" + tag + "Init", f(b2["rel_pid_init"], 3))
    put("bench" + tag + "RsmGain", f(100 * (1 - b2["rel_pid_rsm"] / b2["rel_pid_init"]), 0))
    put("bench" + tag + "Runs", f"{b2['iterations'] * 265}")
    put("bench" + tag + "LoadStatic", f(b["load_static"], 2))
    put("bench" + tag + "LoadPid", f(b["load_pid"], 2))
    put("bench" + tag + "LoadIdeal", "--" if b["load_ideal"] is None else f(b["load_ideal"], 2))
    put("bench" + tag + "Gain", f((1 - b["pid"] / b["static_opt"]) * 100, 0))

hs = json.load(open("results/rsm_iae_history_staticinit.json"))
I0 = perf["No decoupler"]["IAE_rel_setpoint"]
iae_none = best["IAE"] / best["IAE_rel"]
put("staticInitIAErel", f(min(h["J_center"] for h in hs) / iae_none, 4))
put("staticInitIter", str(len(hs)))
put("pidIAErelFour", f(best["IAE_rel"], 4))
put("staticIAErelFour", f(perf["Static decoupler"]["IAE_rel_setpoint"], 4))
b2 = [json.load(open(f"results/bench2_{n}_hist.json")) for n in ["Hylte", "WoodBerry"]]
put("benchMinRtwo", f(min(min(x["r2"] for x in h) for h in b2), 2))
with open("results/results_macros.tex", "w") as fh:
    fh.write("% Auto-generated by gen_macros.py -- do not edit by hand\n")
    for k, v in M.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(f"{len(M)} macros written")
